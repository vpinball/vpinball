   inline vec3 HSVToSRGB(const vec3& hsv)
   {
      if (hsv.y == 0.0f)
         return vec3 { hsv.z, hsv.z, hsv.z }; // gray
 
      const float h = (hsv.x - floorf(hsv.x)) * (float)(360.0 / 60.0);
      int i = static_cast<int>(h);
      float f = h - static_cast<float>(i);
      float p = hsv.z * (1.0f - hsv.y);
      float q = hsv.z * (1.0f - hsv.y * f);
      float t = hsv.z * (1.0f - hsv.y * (1.0f - f));
      switch (i)
      {
      case 0: return { hsv.z, t, p };
      case 1: return { q, hsv.z, p };
      case 2: return { p, hsv.z, t };
      case 3: return { p, q, hsv.z };
      case 4: return { t, p, hsv.z };
      case 5:
      default: return { hsv.z, p, q };
      }
   }

   inline vec3 SRGBToHSV(const vec3& srgb)
   {
      float r = srgb.x;
      float g = srgb.y;
      float b = srgb.z;

      float max = std::max({ r, g, b });
      float min = std::min({ r, g, b });
      float delta = max - min;

      float h = 0.0f;
      float s = 0.0f;
      float v = max;

      if (delta > 0.0f)
      {
         s = delta / max;

         if (r == max)
            h = (g - b) / delta;
         else if (g == max)
            h = 2.0f + (b - r) / delta;
         else // b == max
            h = 4.0f + (r - g) / delta;

         h *= 60.0f;
         if (h < 0.0f)
            h += 360.0f;
      }

      return { h, s, v };
   }

